/** Today's date as dd.mm.yyyy. */
export function todayLabel(date = new Date()) {
  const dd = String(date.getDate()).padStart(2, "0");
  const mm = String(date.getMonth() + 1).padStart(2, "0");
  return `${dd}.${mm}.${date.getFullYear()}`;
}

export function makeSection(kind, headingText = "", itemTexts = []) {
  return {
    id: newId(),
    kind,
    heading: headingText ? docFromText(headingText, { underline: true }) : null,
    items: itemTexts.map((text) => ({ id: newId(), content: docFromText(text) })),
  };
}

export function emptyNotice() {
  return {
    header: { ...DEFAULT_HEADER },
    noticeDate: todayLabel(),
    sections: SECTION_TEMPLATES.map((t) => makeSection(t.kind, t.heading)),
    signature: { ...DEFAULT_SIGNATURE },
  };
}

